// BLOCK 3: BODY BLOCK
// ( Core Restoration Pipeline: Boundaries, 4-Block Headers, Imports, Verification )
// ==============================================================================
impl Restorator {
    /// Restores source code in memory, executing multi-pass auto-repairs.
    ///
    /// Executes the 5-pass self-healing pipeline:
    /// 1. Delimiter & Boundary Healing
    /// 2. 4-Block Architectural Scaffolding Healing
    /// 3. Automated Dependency & Import Healing
    /// 4. Inferred Conceptual Entity Healing
    /// 5. Round-trip Lint/Parse/Eval Verification
    ///
    /// # Arguments
    /// * `source` - Raw input string that may contain boundary leaks or syntax anomalies.
    ///
    /// # Returns
    /// A [`RestorationReport`] detailing all modifications and verification proofs.
    pub fn restore_source(&self, source: &str) -> RestorationReport {
        let original_content = source.to_string();
        let mut current = source.to_string();
        let mut repairs_applied = Vec::new();

        // Pass 1: Delimiter & Boundary Healing
        current = self.heal_boundaries(&current, &mut repairs_applied);

        // Pass 2: 4-Block Architectural Scaffolding Healing
        current = self.heal_four_blocks(&current, &mut repairs_applied);

        // Pass 3: Automated Dependency & Import Healing
        current = self.heal_imports(&current, &mut repairs_applied);

        // Pass 4: Inferred Conceptual Entity Healing
        current = self.heal_inferred_entities(&current, &mut repairs_applied);

        // Pass 5: Round-trip Self-Verification
        let (verified, final_state, errors) = self.verify_restoration(&current);

        let was_modified = current != original_content;

        if !repairs_applied.is_empty() {
            RestoratorTelemetry::record_repairs_applied(&self.logger, &repairs_applied);
        }

        RestorationReport {
            file_path: None,
            was_modified,
            original_content,
            restored_content: current,
            repairs_applied,
            verified,
            final_state,
            errors,
        }
    }

    /// Evaluates the 2-Way Checksum agreement between the DiagnosticLogger and OmniDebugger.
    pub fn evaluate_two_way_checksum(&self, debugger: &OmniDebugger, candidate_source: &str) -> TwoWayAgreement {
        RestoratorCertifier::evaluate_two_way_checksum(&self.logger, debugger, candidate_source)
    }

    /// Ingests a structured [`LogEvent`] and executes a targeted, single-point surgical patch.
    ///
    /// # Arguments
    /// * `source` - Source code to repair.
    /// * `log` - Structured incident event containing a [`crate::diagnostics::logger::FixSuggestion`].
    ///
    /// # Returns
    /// [`RestorationReport`] showing the single-point modification and round-trip verification status.
    pub fn restore_from_incident_log(&self, source: &str, log: &LogEvent) -> RestorationReport {
        let original_content = source.to_string();
        let mut repairs_applied = Vec::new();
        let mut current = source.to_string();

        if let Some(sug) = &log.suggestion {
            match sug.kind {
                FixKind::FixBoundaryMismatch => {
                    let lines: Vec<&str> = current.lines().collect();
                    if sug.line > 0 && sug.line <= lines.len() {
                        let mut target_line = lines[sug.line - 1].to_string();
                        if let Some(pos) = target_line.find(&sug.target_token) {
                            target_line.replace_range(pos..pos + sug.target_token.len(), &sug.suggested_patch);
                            let mut new_lines = lines.clone();
                            new_lines[sug.line - 1] = &target_line;
                            current = new_lines.join("\n");
                            if !current.ends_with('\n') {
                                current.push('\n');
                            }
                            repairs_applied.push(AppliedRepair {
                                kind: FixKind::FixBoundaryMismatch,
                                description: sug.rationale.clone(),
                                line: sug.line,
                            });
                        }
                    }
                }
                FixKind::CloseBoundary => {
                    current.push_str(&sug.suggested_patch);
                    if !current.ends_with('\n') {
                        current.push('\n');
                    }
                    repairs_applied.push(AppliedRepair {
                        kind: FixKind::CloseBoundary,
                        description: sug.rationale.clone(),
                        line: sug.line,
                    });
                }
                FixKind::ConvertImmutableToMutable => {
                    current = current.replace(&format!("< {} >", sug.target_token), &sug.suggested_patch);
                    repairs_applied.push(AppliedRepair {
                        kind: FixKind::ConvertImmutableToMutable,
                        description: sug.rationale.clone(),
                        line: sug.line,
                    });
                }
                _ => {
                    current = current.replace(&sug.target_token, &sug.suggested_patch);
                    repairs_applied.push(AppliedRepair {
                        kind: sug.kind.clone(),
                        description: sug.rationale.clone(),
                        line: sug.line,
                    });
                }
            }
        }

        let (verified, final_state, errors) = self.verify_restoration(&current);
        let was_modified = current != original_content;

        if was_modified {
            RestoratorTelemetry::record_log_driven_fix(
                &self.logger,
                &format!("{:?}", log.failpoint_type),
                current.len(),
            );
        }

        RestorationReport {
            file_path: None,
            was_modified,
            original_content,
            restored_content: current,
            repairs_applied,
            verified,
            final_state,
            errors,
        }
    }

    /// Restores source code and executes an external verification test oracle against the candidate.
    ///
    /// Connects the self-healing engine to test harnesses:
    /// - If the restored code satisfies the test oracle: logs an `ORACLE_CERTIFIED` cognitive trace.
    /// - If the test oracle fails: records a rollback failpoint and adds the failure to the report errors.
    ///
    /// # Arguments
    /// * `source` - Raw input code.
    /// * `test_oracle` - Closure asserting domain-specific invariants on the restored source.
    pub fn restore_and_verify_with_oracle<F>(&self, source: &str, test_oracle: F) -> RestorationReport
    where
        F: Fn(&str) -> Result<(), String>,
    {
        let mut report = self.restore_source(source);

        if report.verified {
            if let Err(err) = RestoratorCertifier::verify_with_test_oracle(&report.restored_content, test_oracle, &self.logger) {
                report.verified = false;
                report.errors.push(format!("Test oracle failure: {err}"));
            }
        }

        report
    }

    /// Restores a file from disk, optionally writing back the healed source in-place.
    ///
    /// # Arguments
    /// * `path` - File system path to the target source file.
    /// * `in_place` - If true, overwrites the file on disk with the restored content.
    ///
    /// # Errors
    /// Returns `Err(String)` if file reading or writing fails.
    pub fn restore_file(&self, path: &str, in_place: bool) -> Result<RestorationReport, String> {
        let content = fs::read_to_string(path)
            .map_err(|e| format!("Failed to read file '{path}': {e}"))?;

        let mut report = self.restore_source(&content);
        report.file_path = Some(path.to_string());

        if in_place && report.was_modified {
            fs::write(path, &report.restored_content)
                .map_err(|e| format!("Failed to write restored file '{path}': {e}"))?;
            RestoratorTelemetry::log_in_place_write(&self.logger, path);
        }

        Ok(report)
    }

    /// Pass 1: Auto-detects and repairs mismatched and leaking delimiters.
    pub fn heal_boundaries(&self, source: &str, repairs: &mut Vec<AppliedRepair>) -> String {
        BoundaryHealer::heal(source, repairs)
    }

    /// Pass 2: Ensures all 4 universal architectural blocks exist in canonical order.
    pub fn heal_four_blocks(&self, source: &str, repairs: &mut Vec<AppliedRepair>) -> String {
        ScaffoldingHealer::heal(source, repairs)
    }

    /// Pass 3: Automatically injects missing core library imports into Opening block.
    pub fn heal_imports(&self, source: &str, repairs: &mut Vec<AppliedRepair>) -> String {
        ImportHealer::heal(source, repairs)
    }

    /// Pass 4: Resolves and declares undefined conceptual nouns with infer operator `?`.
    pub fn heal_inferred_entities(&self, source: &str, repairs: &mut Vec<AppliedRepair>) -> String {
        InferredTypeHealer::heal(source, repairs)
    }

    /// Pass 5: Evaluates restored code to verify complete execution without failpoints.
    pub fn verify_restoration(&self, source: &str) -> (bool, Option<QuadState>, Vec<String>) {
        RestoratorCertifier::verify_restoration(source)
    }
}

