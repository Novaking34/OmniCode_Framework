/// Record of an individual restorative patch applied to source code.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AppliedRepair {
    /// The structural category of the applied repair.
    pub kind: FixKind,
    /// Detailed human and AI-readable explanation of why and how the repair was made.
    pub description: String,
    /// 1-based source line number where the repair took effect.
    pub line: usize,
}

/// Comprehensive outcome report generated by the [`Restorator`].
///
/// Contains original source, restored content, applied repairs, verification status,
/// and any errors encountered during the self-healing cycle.
#[derive(Debug, Clone, PartialEq)]
pub struct RestorationReport {
    /// File path if restoration was performed on disk, or `None` if in-memory.
    pub file_path: Option<String>,
    /// `true` if any modifications or repairs were made to the source text.
    pub was_modified: bool,
    /// Exact unmodified original source code prior to healing passes.
    pub original_content: String,
    /// Healed, patched, and structurally validated source code.
    pub restored_content: String,
    /// Chronological list of all automated repairs applied during the cycle.
    pub repairs_applied: Vec<AppliedRepair>,
    /// `true` if the restored content passed all lint, parse, and evaluation checks.
    pub verified: bool,
    /// The final QuadState produced by evaluating the restored source (+1:PROCEED).
    pub final_state: Option<QuadState>,
    /// Any lint, parse, or evaluation errors if verification failed.
    pub errors: Vec<String>,
}

/// The autonomous self-healing and code restoration engine.
#[derive(Debug, Clone)]
pub struct Restorator {
    /// Shared diagnostic logger recording cognitive observations and repair history.
    pub logger: DiagnosticLogger,
}

impl Restorator {
    /// Constructs a new [`Restorator`] instance bound to the provided logger.
    pub fn new(logger: DiagnosticLogger) -> Self {
        Self { logger }
    }
}

