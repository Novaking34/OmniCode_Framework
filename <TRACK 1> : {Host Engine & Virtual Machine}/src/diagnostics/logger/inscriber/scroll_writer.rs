#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_inscribe_canonical_scroll_4block_structure() {
        let temp_dir = std::env::temp_dir().join(format!("omnicode_scroll_test_{}", std::process::id()));
        let scroll_path = temp_dir.join("test_session.scroll");

        let res = inscribe_canonical_scroll(
            &scroll_path,
            "sess_scroll_01",
            "Evaluate balanced ternary addition",
            "{ (+1) + (-1) = 0 }",
            "PROCEED",
            "Equation holds in perfect equilibrium",
            1280,
        )
        .unwrap();

        assert_eq!(res, scroll_path);
        let content = fs::read_to_string(&scroll_path).unwrap();
        assert!(content.contains("BLOCK 1: METADATA BLOCK"));
        assert!(content.contains("BLOCK 2: OPENING BLOCK"));
        assert!(content.contains("BLOCK 3: BODY BLOCK"));
        assert!(content.contains("BLOCK 4: CLOSING BLOCK"));
        assert!(content.contains("sess_scroll_01"));
        assert!(content.contains("commit_status [ <PROCEED> ]"));
        assert!(content.contains("user_prompt < \"Evaluate balanced ternary addition\" >"));

        fs::remove_dir_all(&temp_dir).ok();
    }

    #[test]
    fn test_inscribe_audit_scroll_generation() {
        let note1 = CognitiveNote {
            timestamp_micros: 100,
            category: "INCIDENT".to_string(),
            summary: "Boundary tripwire caught".to_string(),
            details: "Unclosed delimiter at L12".to_string(),
            tags: vec!["failpoint".to_string(), "syntax".to_string()],
            context_snippet: Some("{ Cell ]".to_string()),
        };

        let audit = inscribe_audit_scroll(std::slice::from_ref(&note1), 1);
        assert!(audit.contains("< CognitiveMemory { Audit } >"));
        assert!(audit.contains("[ Total Notes ]:      { 1 }"));
        assert!(audit.contains("commit_status [ <PROCEED> ]"));
    }

    #[test]
    fn test_inscribe_kernel_audit_scroll() {
        let temp_dir = std::env::temp_dir().join(format!("omnicode_kscroll_test_{}", std::process::id()));
        let kscroll_path = temp_dir.join("kernel_genesis.scroll");

        let log1 = GenesisBootLog::new(
            500,
            0x7C00,
            "BIOS_REAL_MODE",
            "16-Bit Genesis: OK",
            "GENESIS_BOOT",
            true,
        );
        let log2 = GenesisBootLog::new(
            1200,
            0x18000,
            "STAGE2_PM",
            "32-Bit Protected Mode Active: OK",
            "REGS_CALIBRATED",
            true,
        );

        let logs = vec![log1, log2];
        inscribe_kernel_audit_scroll(&kscroll_path, "kgen_01", &logs, true).unwrap();
        let content = fs::read_to_string(&kscroll_path).unwrap();
        assert!(content.contains("MilleniumOS { KernelGenesis }"));
        assert!(content.contains("[ Milestones ]:  { 2 }"));
        assert!(content.contains("0x00018000"));
        assert!(content.contains("STAGE2_PM"));
        assert!(content.contains("commit_status [ <PROCEED> ]"));

        fs::remove_dir_all(&temp_dir).ok();
    }
}
